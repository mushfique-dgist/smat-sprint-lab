def first_sentence(text: str) -> str:
    text = re.sub(r"\s+", " ", text or "").strip()
    m = re.match(r"(.{20,220}?[.!?])(\s|$)", text)
    return (m.group(1) if m else text[:220]).replace("|", "/")


def main() -> None:
    out = ["# What was done with each finding of the adversarial review",
           "",
           "Six lenses reviewed the master prompt on 2026-09-23 (the lens files are beside this one). Every finding is",
           "listed with its severity, the first sentence of its problem, and what was done. Where a status names a part,",
           "the fix text is in that part of `parts/` and in the assembled `CODEX_MASTER_PROMPT.md`. The canonical names",
           "and numbers the editors used are in `DECISIONS_FOR_APPLYING.md`.",
           ""]
    total = counted = 0
    for fname, title in LENSES:
        d = json.loads((HERE / fname).read_text(encoding="utf-8"))
        fs = d["findings"]
        out += [f"## {title}: {len(fs)} findings", "", "| Id | Severity | Problem (first sentence) | What was done |", "|---|---|---|---|"]
        for f in fs:
            fid = f.get("id", "?")
            total += 1
            st = STATUS.get(fid, "NOT RECORDED")
            if fid in STATUS:
                counted += 1
            out.append(f"| {fid} | {f.get('severity', '')} | {first_sentence(f.get('problem', ''))} | {st.replace('|', '/')} |")
        out.append("")
    (HERE / "APPLIED.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"APPLIED.md: {total} findings, {counted} with a recorded status")


